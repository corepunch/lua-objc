_G.__headless = true
local t=require("TestKit")
local Git=require("Git")
local bridge=require("AppKitNative")
local pipe=assert(io.popen("/usr/bin/mktemp -d /private/tmp/git-remote.XXXXXXXX"))
local root=pipe:read("*l"); pipe:close()
local function write(repo,name,text)
	local file=assert(io.open(repo:workdir()..name,"w"));file:write(text);file:close()
end
local author={name="Test",email="test@example.com"}
local bare=assert(Git.init(root.."/origin",{bare=true}))
local repo=assert(Git.init(root.."/local"))
write(repo,"init.lua","return 1\n");assert(repo:add());local first=assert(repo:commit("First",author))
t.expect(repo:setRemote("origin","file://"..root.."/origin"),"add a remote through libgit2")
t.assertEqual(repo:remotes()[1].url,"file://"..root.."/origin","remote config is persistent")
t.expect(not pcall(repo.setRemote,repo,"unsafe","https://token@github.com/owner/repo.git"),"never persist credentials in remote URLs")
t.expect(not pcall(repo.setRemote,repo,"unsafe","http://github.com/owner/repo.git"),"plaintext HTTP is rejected")
local done,ok,err
local function completed(success,message) done,ok,err=true,success,message end
local function wait()
	for _=1,100 do if done then break end;bridge._runLoopTick(0.005) end
	t.expect(done,"libgit2 completion reaches Lua on the main run loop")
end
local transfer=assert(repo:push("origin",{},completed))
wait();t.expect(ok,err or "push succeeds")
t.assertEqual(bare:head().id,first,"remote HEAD contains the actual local commit")
t.assertEqual(bare:show("HEAD","init.lua"),"return 1\n","remote has project source")
write(repo,"init.lua","return 2\n");repo:add();local second=assert(repo:commit("Second",author))
done=false;transfer=assert(repo:push("origin",{},completed));repo:close();wait()
t.expect(ok,"closing a local handle does not free a worker's independent repository")
t.assertEqual(bare:head().id,second,"subsequent pushes retain history")
local other=assert(Git.init(root.."/diverged"));write(other,"init.lua","return 99\n");other:add();other:commit("Unrelated",author)
other:setRemote("origin","file://"..root.."/origin")
done=false;transfer=assert(other:push("origin",{},completed));wait()
t.expect(not ok and type(err)=="string","non-fast-forward pushes report a rejection")
t.assertEqual(bare:head().id,second,"remote history is never force overwritten")
done=false;transfer=assert(other:push("origin",{},completed));transfer:cancel();wait()
t.expect(not ok and err:find("cancelled",1,true),"cancelled transfers do not report success")
t.expect(other:setRemote("review","file://"..root.."/origin","app-review"),"configure a separate GitHub review branch")
t.assertEqual(other:remotes()[2].branch,"app-review","destination branch is persisted without credentials")
done=false;transfer=assert(other:push("review",{},completed));wait()
t.expect(ok,"a new remote branch accepts independent local history without overwriting main")
t.assertEqual(bare:show("app-review","init.lua"),"return 99\n","the chosen branch contains the published source")
t.assertEqual(bare:head().id,second,"publishing a review branch preserves main")
t.expect(not pcall(other.setRemote,other,"bad","file://"..root.."/origin","bad..branch"),"invalid refs are rejected before changing remote config")
other:close();bare:close();os.execute("/bin/rm -rf "..root)
os.exit(t.summary() and 0 or 1)
